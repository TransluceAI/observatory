"""Utils for generating (question, answer) pairs for training the LatentQA decoder."""

import json
import random
import re
from enum import Enum
from typing import Any, Generic, Literal, Type, TypeVar

from latentqa.mc_util import get_all_mc_option_keys
from latentqa.qa_prompt_templates import GENERAL_PROMPT, MULTIPLE_CHOICE_PROMPT, SETUP_PROMPT
from llm_util.types import Usage
from pydantic import BaseModel
from user_modeling.llm_util import DataGeneratorConfig, get_llm_completion_strs_async
from user_modeling.synthsys.subject_inputs import MinimalSubjectInput
from user_modeling.user_attribute import UserAttribute


class QACategory(str, Enum):
    DIRECT = "direct"
    INDIRECT = "indirect"
    UNANSWERABLE = "unanswerable"
    MC = "multiple_choice"
    DUMMY = "dummy"


# Question content types
class QuestionContent(BaseModel):
    """Base class for different types of question content"""


class CompletedQuestion(QuestionContent):
    """Fully formed question ready for use"""

    question: str


class IncompleteMultipleChoice(QuestionContent):
    """Multiple choice components that need formatting"""

    stem: str
    distractors: list[str]


# Generic base QA class
T = TypeVar("T", bound=QuestionContent)


class BaseQA(BaseModel, Generic[T]):
    """Base QA class generic over question content type"""

    attr_class: Type[UserAttribute]
    attr: UserAttribute
    qa_category: QACategory | None = None
    answer: str
    content: T

    # Fields for when the QA is generated by an LLM.
    model_name: str | None = None
    prompt_used_to_generate_prompt: list[dict[str, Any]] | None = None
    usage: Usage | None = None

    def __eq__(self, other: object) -> bool:
        """Compare two QAs based on their core fields"""
        if not isinstance(other, BaseQA):
            return NotImplemented

        return (
            self.content == other.content
            and self.answer == other.answer
            and self.attr_class == other.attr_class
            and self.attr == other.attr
        )

    def __hash__(self) -> int:
        """Generate a hash based on the core fields"""
        return hash(
            (
                self.content,
                self.answer,
                self.attr_class,
                self.attr,
            )
        )


class InvalidContext(BaseModel):
    attr_class: Type[UserAttribute]
    attr: UserAttribute
    user_prompt: str
    completion: str
    model_name: str
    prompt_used_to_generate_prompt: list[dict[str, Any]]
    reasoning: str
    id: int | None = None
    usage: Usage | None = None


class ContextCondQA(BaseQA[T]):
    """LLM-generated QA that is conditioned on a conversation between a user and a subject model."""

    user_prompt: str
    completion: str
    validation_reasoning: str | None
    """
    This is set when we ask the LLM to validate the conversation first by checking if
    the completion is consistent with the user attribute.
    """


# Convenient type aliases
CompletedContextCondQA = ContextCondQA[CompletedQuestion]
IncompleteContextCondQA = ContextCondQA[IncompleteMultipleChoice]


class QAGenerator:
    """
    Handles generation of (question, answer) pairs. These QAs are conditioned on the conversation
    between the user and the subject model.
    """

    FREEFORM_FORMAT = """Mix of open-ended, fill-in-the-blank, "what/why/how" questions."""
    MC_FORMAT = "At least one multiple choice question, where the answer is option {answer} out of {num_options} options. The rest of the questions should be a mix of open-ended, fill-in-the-blank, 'what/why/how' questions."
    YESNO_FORMAT = "At least one yes/no question, where the answer is {answer}. The rest of the questions should be a mix of open-ended, fill-in-the-blank, 'what/why/how' questions."

    def __init__(
        self,
        generation_config: DataGeneratorConfig,
        rng: random.Random,
        question_type: Literal["general", "multiple_choice"] = "general",
        format_probs: tuple[float, float, float] = (0.6, 0.25, 0.15),
    ):
        self.generation_config = generation_config
        self.question_type = question_type
        self.format_probs = format_probs
        self.rng = rng

        self.mc_option_keys_cache: dict[int, list[str]] = {}

    def _get_general_generation_prompt(self, conversation_str: str, main_thought: str) -> str:
        """Get the generation prompt for a general question type"""

        format = self.rng.choices(["freeform", "mc", "yesno"], weights=self.format_probs, k=1)[0]
        if format == "mc":
            num_options = self.rng.choice(range(2, 5))
            mc_option_keys = self.mc_option_keys_cache.get(
                num_options, get_all_mc_option_keys(num_options)
            )
            assert mc_option_keys is not None
            self.mc_option_keys_cache[num_options] = mc_option_keys
            answer = self.rng.choice(mc_option_keys)
            format = self.MC_FORMAT.format(answer=answer, num_options=num_options)
        elif format == "yesno":
            answer = self.rng.choice(["yes", "no"])
            format = self.YESNO_FORMAT.format(answer=answer)
        else:
            format = self.FREEFORM_FORMAT

        return GENERAL_PROMPT.format(
            setup=SETUP_PROMPT,
            format=format,
            conversation=conversation_str,
            main_thought=main_thought,
        )

    def _get_generation_prompt(
        self, attribute: UserAttribute, user_prompt: str, completion: str
    ) -> str:
        """Get the generation prompt for a given attribute class"""
        conversation = [
            {"role": "user", "content": user_prompt},
            {"role": "assistant", "content": completion},
        ]
        conversation_str = "\n".join(msg.__repr__() for msg in conversation)
        main_thought = f"The {attribute.attribute_name} is {attribute.value_name}"

        if self.question_type == "general":
            return self._get_general_generation_prompt(conversation_str, main_thought)
        elif self.question_type == "multiple_choice":
            return MULTIPLE_CHOICE_PROMPT.format(
                setup=SETUP_PROMPT,
                conversation=conversation_str,
                main_thought=main_thought,
            )
        else:
            raise ValueError(f"Invalid question type: {self.question_type}")

    def _parse_generation_response_for_general(
        self,
        response: str,
        attribute: UserAttribute,
        user_prompt: str,
        completion: str,
        messages_for_generation: list[dict[str, Any]],
    ) -> list[CompletedContextCondQA] | InvalidContext:
        """
        Parse the LLM's generation response into QA objects, matching the expected template format.
        """

        qas: list[CompletedContextCondQA] = []
        try:
            # Try to extract the JSON object from the response
            json_match = re.search(r"\{.*\}", response, re.DOTALL)
            if json_match:
                json_str = json_match.group()
                data = json.loads(json_str)

                if data["correct"]:
                    for category in ["direct", "indirect"]:
                        qa_list = data.get(category, [])
                        for item in qa_list:
                            if isinstance(item, dict):
                                qas.append(
                                    CompletedContextCondQA(
                                        attr_class=attribute.__class__,
                                        attr=attribute,
                                        qa_category=QACategory(category),
                                        content=CompletedQuestion(question=item["question"]),
                                        answer=item["answer"],
                                        model_name=self.generation_config.model_name,
                                        prompt_used_to_generate_prompt=messages_for_generation,
                                        user_prompt=user_prompt,
                                        completion=completion,
                                        validation_reasoning=data["reasoning"],
                                    )
                                )
                    if len(qas) < 4:  # 2 direct + 2 indirect
                        return []
                else:
                    return InvalidContext(
                        attr_class=attribute.__class__,
                        attr=attribute,
                        user_prompt=user_prompt,
                        completion=completion,
                        model_name=self.generation_config.model_name,
                        prompt_used_to_generate_prompt=messages_for_generation,
                        reasoning=data["reasoning"],
                    )
        except Exception as e:
            print(e)

        return qas

    def _parse_generation_response_for_multiple_choice(
        self,
        response: str,
        attribute: UserAttribute,
        user_prompt: str,
        completion: str,
        messages_for_generation: list[dict[str, Any]],
    ) -> list[IncompleteContextCondQA] | InvalidContext:
        """
        Parse the LLM's generation response into QA objects, matching the expected template format.
        """

        qas: list[IncompleteContextCondQA] = []
        try:
            # Try to extract the JSON object from the response
            json_match = re.search(r"\{.*\}", response, re.DOTALL)
            if json_match:
                json_str = json_match.group()
                data = json.loads(json_str)

                if data["correct"]:
                    for category in ["direct", "indirect"]:
                        qa_list = data.get(category, [])
                        for item in qa_list:
                            if isinstance(item, dict):
                                if (
                                    "distractors" not in item
                                    or "question" not in item
                                    or "answer" not in item
                                ):
                                    continue

                                qas.append(
                                    IncompleteContextCondQA(
                                        attr_class=attribute.__class__,
                                        attr=attribute,
                                        qa_category=QACategory(category),
                                        content=IncompleteMultipleChoice(
                                            stem=item["question"], distractors=item["distractors"]
                                        ),
                                        answer=item["answer"],
                                        model_name=self.generation_config.model_name,
                                        prompt_used_to_generate_prompt=messages_for_generation,
                                        user_prompt=user_prompt,
                                        completion=completion,
                                        validation_reasoning=data.get("reasoning"),
                                    )
                                )
                else:
                    return InvalidContext(
                        attr_class=attribute.__class__,
                        attr=attribute,
                        user_prompt=user_prompt,
                        completion=completion,
                        model_name=self.generation_config.model_name,
                        prompt_used_to_generate_prompt=messages_for_generation,
                        reasoning=data.get("reasoning"),
                    )
        except Exception as e:
            print(e)

        return qas

    async def generate_qas(
        self,
        user_prompt: str,
        completion: str,
        attribute: UserAttribute,
        use_cache: bool = True,
    ) -> list[CompletedContextCondQA] | list[IncompleteContextCondQA] | InvalidContext:
        """Generate (question, answer) pairs for a given conversation and attribute."""

        # Construct the prompt for the generator LLM.
        prompt = self._get_generation_prompt(attribute, user_prompt, completion)
        messages = [{"role": "user", "content": prompt}]

        # Query LLM for generation.
        responses, usages = await get_llm_completion_strs_async(
            [messages], config=self.generation_config, use_cache=use_cache
        )
        response = responses[0]
        usage = usages[0]

        if self.question_type == "general":
            out = self._parse_generation_response_for_general(
                response, attribute, user_prompt, completion, messages
            )
        elif self.question_type == "multiple_choice":
            out = self._parse_generation_response_for_multiple_choice(
                response, attribute, user_prompt, completion, messages
            )
        else:
            raise ValueError(f"Invalid question type: {self.question_type}")

        if isinstance(out, InvalidContext):
            out.usage = usage
            return out

        if len(out) > 0:
            divided_usage = usage.divide(len(out))
            for qa in out:
                qa.usage = divided_usage
        return out

    async def generate_qas_batch(
        self, subject_inputs: list[MinimalSubjectInput], use_cache: bool = True
    ) -> list[list[CompletedContextCondQA] | list[IncompleteContextCondQA] | InvalidContext]:
        messages_list: list[list[dict[str, str]]] = []
        for si in subject_inputs:
            prompt = self._get_generation_prompt(
                attribute=si.attr, user_prompt=si.user_prompt, completion=si.completion
            )
            messages_list.append([{"role": "user", "content": prompt}])

        responses, usages = await get_llm_completion_strs_async(
            messages_list,
            config=self.generation_config,
            use_cache=use_cache,
        )

        outs: list[
            list[CompletedContextCondQA] | list[IncompleteContextCondQA] | InvalidContext
        ] = []
        for i, (response, usage) in enumerate(zip(responses, usages)):
            if self.question_type == "general":
                out = self._parse_generation_response_for_general(
                    response, si.attr, si.user_prompt, si.completion, messages_list[i]
                )
            elif self.question_type == "multiple_choice":
                out = self._parse_generation_response_for_multiple_choice(
                    response, si.attr, si.user_prompt, si.completion, messages_list[i]
                )
            else:
                raise ValueError(f"Invalid question type: {self.question_type}")

            if isinstance(out, InvalidContext):
                out.usage = usage
            elif len(out) > 0:
                divided_usage = usage.divide(len(out))
                for qa in out:
                    qa.usage = divided_usage
            outs.append(out)
        return outs
